from pathlib import Path
import sys,tempfile,json,os
from unittest.mock import patch
from playwright.sync_api import sync_playwright,expect
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from desktop import DesktopServer
out=ROOT.parent/'build'/'qa-future';out.mkdir(parents=True,exist_ok=True)
errors=[]
with tempfile.TemporaryDirectory(dir=out) as tmp, patch.dict(os.environ,{'LLM_MODEL':'','LLM_API_KEY':'','LLM_BASE_URL':''}):
 backend=DesktopServer(Path(tmp)/'data',preferred_port=0).start()
 try:
  with sync_playwright() as pw:
   browser=pw.chromium.launch(channel='msedge',headless=True)
   page=browser.new_page(viewport={'width':1320,'height':900})
   page.on('pageerror',lambda error:errors.append(str(error)))
   page.goto(backend.url+'/#future',wait_until='networkidle')
   expect(page.locator('[data-view="documents"]')).to_have_text('文档')
   expect(page.locator('#view-future')).to_be_visible()
   expect(page.locator('#future-list')).to_contain_text('先收藏，等有精力再学')
   page.locator('#add-future').click()
   form=page.locator('#future-form')
   form.locator('[name="title"]').fill('理解 KV Cache：先收藏，有空再学')
   form.locator('[name="subject"]').fill('人工智能')
   form.locator('[name="url"]').fill('https://example.com/kv-cache')
   form.locator('[name="content"]').fill('今天看到了这个概念，暂时没精力深入。以后想弄懂缓存怎样减少重复计算。\n<script>window.bad=true</script>')
   page.screenshot(path=str(out/'editor.png'))
   page.locator('#save-future').click()
   expect(page.locator('#future-dialog')).not_to_be_visible()
   expect(page.locator('.future-card')).to_have_count(1)
   page.reload(wait_until='networkidle')
   expect(page.locator('.future-card h2')).to_contain_text('KV Cache')
   page.locator('.future-notes summary').click()
   expect(page.locator('.future-notes p')).to_contain_text('<script>')
   assert page.evaluate('window.bad') is None
   page.screenshot(path=str(out/'collection.png'))
   page.get_by_role('button',name='开始学习 →',exact=True).click()
   expect(page.locator('.future-status')).to_have_text('学习中')
   page.locator('#future-filter').select_option('pending')
   expect(page.locator('.future-card')).to_have_count(0)
   page.locator('#future-reset').click()
   expect(page.locator('.future-card')).to_have_count(1)
   page.get_by_role('button',name='标记学完 ✓',exact=True).click()
   expect(page.locator('.future-status')).to_have_text('已学完')
   page.locator('.future-card .entry-edit').click()
   form.locator('[name="content"]').fill('已理解缓存的作用。')
   page.keyboard.press('Control+s')
   expect(page.locator('#future-dialog')).not_to_be_visible()
   page.locator('#future-query').fill('不存在的关键词')
   expect(page.locator('.future-card')).to_have_count(0)
   page.locator('#future-query').fill('缓存')
   expect(page.locator('.future-card')).to_have_count(1)
   page.locator('.future-card .entry-edit').click()
   form.locator('[name="content"]').fill('未保存')
   page.once('dialog',lambda d:d.dismiss())
   page.locator('#cancel-future').click()
   expect(page.locator('#future-dialog')).to_be_visible()
   page.once('dialog',lambda d:d.accept())
   page.locator('#cancel-future').click()
   expect(page.locator('#future-dialog')).not_to_be_visible()
   page.locator('[data-view="documents"]').click()
   expect(page.locator('#view-documents h1')).to_contain_text('文档')
   page.locator('[data-view="future"]').click()
   page.set_viewport_size({'width':960,'height':680})
   page.screenshot(path=str(out/'compact.png'))
   assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
   page.locator('.future-card .entry-edit').click()
   page.once('dialog',lambda d:d.accept())
   page.locator('#delete-future').click()
   expect(page.locator('#future-dialog')).not_to_be_visible()
   expect(page.locator('.future-card')).to_have_count(0)
   assert not errors,errors
   browser.close()
 finally:backend.close()
(out/'result.json').write_text(json.dumps({'ok':True,'errors':errors},indent=2),encoding='utf-8')
print('UI QA passed')
